#!/usr/bin/env python3
"""Turns the specification's sleeping-leaves test vectors into a C header for tests/sleep.c.

    python3 tests/vectors/sleeping_to_c.py tests/vectors/sleeping.json OUT.h

The build runs this; nothing it writes is checked in. Like the others it only reformats: every
value in the header is copied from the JSON, none is computed.
"""

import json
import sys


def hexbytes(h):
    return "{" + ", ".join(f"0x{h[i:i + 2]}" for i in range(0, len(h), 2)) + "}" if h else "{0}"


def b(v):
    return "true" if v else "false"


def main():
    src, out = sys.argv[1], sys.argv[2]
    v = json.load(open(src, encoding="utf-8"))
    ids = v["routing_ids"]
    L = ["/* Generated by tests/vectors/sleeping_to_c.py from tests/vectors/sleeping.json. Do not edit. */", ""]
    L.append(f"#define V_LEAF {ids['leaf']}u")
    L.append(f"#define V_KEEPER {ids['keeper']}u")
    L.append(f"#define V_OTHER {ids['other']}u")

    L.append("static const struct poll_case polls[] = {")
    for c in v["polls"]:
        L.append(
            f"    {{{{{c['sender']}u, {c['keeper']}u, {c['id']}, {c['wake']}, {c['listen']}, "
            f"{c['power']}}}, {hexbytes(c['frame'])}}},"
        )
    L.append("};")

    L.append("static const struct answer_case answers[] = {")
    for c in v["poll_answers"]:
        L.append(
            f"    {{{{{c['sender']}u, {c['leaf']}u, {c['id']}, {c['margin']}, {c['held']}, "
            f"{c['power']}}}, {hexbytes(c['frame'])}}},"
        )
    L.append("};")

    L.append("static const struct held_case helds[] = {")
    for c in v["held_notices"]:
        L.append(
            f"    {{{c['power']}, {c['keeper']}u, {c['destination']}u, {c['tag']}u, "
            f"{hexbytes(c['frame'])}}},"
        )
    L.append("};")

    L.append("static const struct rejected_case rejected[] = {")
    for c in v["rejected"]:
        L.append(f"    {{{json.dumps(c['why'])}, {hexbytes(c['frame'])}, {len(c['frame']) // 2}}},")
    L.append("};")

    L.append("static const struct announce_case announces[] = {")
    for c in v["announces"]:
        named = ", ".join(f"{{{n['id']}u, {n['margin']}}}" for n in c["neighbours"]) or "{0, 0}"
        rts = (
            ", ".join(f"{{{r['destination']}u, {r['seq']}, {r['metric']}}}" for r in c["routes"])
            or "{0, 0, 0}"
        )
        L.append(
            f"    {{{{.sender = {c['sender']}u, .number = {c['number']}, .seq = {c['seq']}, "
            f".relay = {b(c['relay'])}, .starting = {b(c['starting'])}, .promise = {c['promise']}, "
            f".round = {c['round']}, .power = {c['power']}, .named_count = {len(c['neighbours'])}, "
            f".route_count = {len(c['routes'])}, .carries_key = {b(c['carries_key'])}, "
            f".sleeps = {b(c['sleeps'])}, .keeper = {c['keeper']}u, "
            f".named = {{{named}}}, .routes = {{{rts}}}}}, "
            f"{hexbytes(c['seed'])}, {b(c['taken'])}, {len(c['frame']) // 2}, {hexbytes(c['frame'])}}},"
        )
    L.append("};")

    L.append("static const struct sleep_case sleeps[] = {")
    for c in v["sleep"]:
        L.append(
            f"    {{{b('wake' in c)}, {c.get('wake', 0)}, {hexbytes(c['content'])}, "
            f"{len(c['content']) // 2}, {b(c['valid'])}}},"
        )
    L.append("};")

    L.append("static const struct holds_case holds[] = {")
    L += [f"    {{{c['at_ms']}, {c['listen']}, {b(c['holds'])}}}," for c in v["holds"]]
    L.append("};")
    L.append("static const struct poll_id_case poll_ids[] = {")
    L += [
        f"    {{{b(c['last'] is not None)}, {c['last'] or 0}, {c['id']}, {b(c['answers'])}}},"
        for c in v["poll_ids"]
    ]
    L.append("};")
    L.append("static const struct rest_case rests[] = {")
    L += [
        f"    {{{b(c['given_up'] is not None)}, {c['given_up'] or 0}, {b(c['answered'])}, "
        f"{b(c['may_take'])}}},"
        for c in v["keeper_rest"]
    ]
    L.append("};")
    L.append("static const struct hold_for_case hold_fors[] = {")
    L += [f"    {{{c['wake']}, {c['hold_for']}}}," for c in v["hold_for"]]
    L.append("};")
    L.append("static const struct wait_case waits[] = {")
    L += [f"    {{{c['metric']}, {c['wake']}, {c['wait_ms']}}}," for c in v["source_waits"]]
    L.append("};")

    p = v["parameters"]
    L.append(f"#define V_WAKE_MIN {p['WAKE_MIN']}")
    L.append(f"#define V_WAKE_MAX {p['WAKE_MAX']}")
    L.append(f"#define V_LISTEN_MIN {p['LISTEN_MIN']}")
    L.append(f"#define V_HOLD_EXTRA {p['HOLD_EXTRA']}")
    L.append(f"#define V_KEEPER_REST {p['KEEPER_REST']}")
    L.append(f"#define V_ACK_WAIT_MS {p['ACK_WAIT_ms']}")
    L.append(f"#define V_ACK_FACTOR {p['ACK_FACTOR']}")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
