#!/usr/bin/env python3
"""Turns the specification's airtime budget test vectors into a C header for tests/airtime.c.

    python3 tests/vectors/airtime_to_c.py tests/vectors/airtime.json OUT.h

The build runs this; nothing it writes is checked in. Like the others it only reformats: every
value in the header is copied from the JSON, none is computed. A profile is named by its region,
and a part or allowance by the core's own names for them.
"""

import json
import sys

PARTS = {"own": "TERN_AIRTIME_OWN", "relayed": "TERN_AIRTIME_RELAYED",
         "routing": "TERN_AIRTIME_ROUTING"}
UNPAID = {None: "TERN_AIRTIME_ROUTES", "waits": "TERN_AIRTIME_WAITS",
          "dropped": "TERN_AIRTIME_DROPPED", "sent": "TERN_AIRTIME_SENT"}
FLOODS = {None: "ALLOWANCE_NONE", "flood_own": "ALLOWANCE_OWN", "flood_relay": "ALLOWANCE_RELAY"}


def b(v):
    return "true" if v else "false"


def nullable(v):
    return "-1" if v is None else str(v)


def main():
    src, out = sys.argv[1], sys.argv[2]
    v = json.load(open(src, encoding="utf-8"))
    L = ["/* Generated by tests/vectors/airtime_to_c.py from tests/vectors/airtime.json. Do not edit. */", ""]

    L.append("static const struct parts_case parts_cases[] = {")
    L += [f"    {{{b(c['role'] == 'relay')}, {c['own_ppm']}, {c['own_window_s']}, "
          f"{nullable(c['relayed_ppm'])}, {nullable(c['relayed_window_s'])}, {c['routing_ppm']}, "
          f"{c['learning_ppm']}, {c['most_ppm']}}}," for c in v["parts"]]
    L.append("};")

    L.append("static const struct class_case class_cases[] = {")
    L += [f"    {{0x{c['hdr']:02x}, {b(c['own'])}, {PARTS[c['part']]}, "
          f"{FLOODS[c['flood_allowance']]}, {UNPAID[c['unpaid']]}}}," for c in v["classes"]]
    L.append("};")

    for i, c in enumerate(v["spends"]):
        L.append(f"static const struct spend_frame spend_frames_{i}[] = {{")
        L += [f"    {{{f['at_ns']}LL, 0x{f['hdr']:02x}, {b(f['own'])}, {f['length']}, "
              f"{f['airtime_ns']}LL, {b(f['sent'])}}}," for f in c["frames"]]
        L.append("};")
    L.append("static const struct spend_case spend_cases[] = {")
    L += [f"    {{\"{c['name']}\", {b(c['role'] == 'relay')}, TERN_REGION_{c['profile']}, "
          f"spend_frames_{i}, {len(c['frames'])}}}," for i, c in enumerate(v["spends"])]
    L.append("};")

    for i, c in enumerate(v["estimates"]):
        L.append(f"static const struct spend_frame estimate_spent_{i}[] = {{")
        L += [f"    {{{f['at_ns']}LL, 0x{f['hdr']:02x}, {b(f['own'])}, {f['length']}, 0, false}},"
              for f in c["spent"]]
        L.append("};")
        L.append(f"static const struct estimate_waiting estimate_waiting_{i}[] = {{")
        L += [f"    {{0x{w['hdr']:02x}, {w['length']}, {w['airtime_ns']}LL, {w['wait_s']}}},"
              for w in c["waiting"]]
        L.append("};")
    L.append("static const struct estimate_case estimate_cases[] = {")
    L += [f"    {{\"{c['name']}\", {b(c['role'] == 'relay')}, TERN_REGION_{c['profile']}, "
          f"estimate_spent_{i}, {len(c['spent'])}, {c['at_ns']}LL, estimate_waiting_{i}, "
          f"{len(c['waiting'])}}}," for i, c in enumerate(v["estimates"])]
    L.append("};")

    L.append("static const struct reason_case reason_cases[] = {")
    L += [f"    {{{b(c['route'])}, {b(c['session'])}, {c['region_wait_s']}u, {c['budget_wait_s']}u, "
          f"{c['reason']}, {c['wait']}}}," for c in v["reasons"]]
    L.append("};")

    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
