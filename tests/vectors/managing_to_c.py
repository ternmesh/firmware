#!/usr/bin/env python3
"""Turns the specification's managing test vectors into a C header for tests/manage.c and
tests/link.c.

    python3 tests/vectors/managing_to_c.py tests/vectors/managing.json OUT.h

The build runs this; nothing it writes is checked in. Like the others it only reformats: every
value in the header is copied from the JSON, none is computed.
"""

import json
import sys


def hexbytes(h):
    return "{" + ", ".join(f"0x{h[i:i + 2]}" for i in range(0, len(h), 2)) + "}" if h else "{0}"


def main():
    src, out = sys.argv[1], sys.argv[2]
    v = json.load(open(src, encoding="utf-8"))
    L = ["/* Generated by tests/vectors/managing_to_c.py from tests/vectors/managing.json. Do not edit. */", ""]
    p = v["parameters"]
    L.append(f"#define V_REQUEST_MAX {p['REQUEST_MAX']}")
    L.append(f"#define V_ANSWER_MAX {p['ANSWER_MAX']}")
    L.append(f"#define V_OWNERS {p['OWNERS']}")
    L.append(f"#define V_TRIAL_S {p['TRIAL']}")

    L.append("static const struct content_case requests[] = {")
    for c in v["requests"]:
        L.append(f"    {{\"{c['why']}\", {hexbytes(c['content'])}, {len(c['content']) // 2}}},")
    L.append("};")
    L.append("static const struct content_case answers[] = {")
    for c in v["answers"]:
        for content in c["contents"]:
            L.append(f"    {{\"{c['why']}\", {hexbytes(content)}, {len(content) // 2}}},")
    L.append("};")
    L.append("static const struct content_case rejected_answers[] = {")
    for c in v["rejected"]:
        L.append(f"    {{\"{c['why']}\", {hexbytes(c['content'])}, {len(c['content']) // 2}}},")
    L.append("};")
    types = {"HELLO": 0x01, "SYNC": 0x02, "PING": 0x03, "SET_TIME": 0x04, "SET": 0x05, "OFF": 0x06,
             "SEND": 0x10, "READ": 0x11, "FORGET": 0x12, "MANAGE": 0x13, "OWNER": 0x14,
             "SAVE_CONTACT": 0x18, "REMOVE_CONTACT": 0x19, "END_SESSION": 0x1A,
             "MAKE_GROUP": 0x20, "LEAVE_GROUP": 0x21, "NAME_GROUP": 0x22, "SEND_GROUP": 0x23,
             "SEND_INVITE": 0x24, "JOIN": 0x25, "GROUP_LINK": 0x26, "JOIN_LINK": 0x27,
             "FORGET_GROUP": 0x28, "UPDATE_BEGIN": 0x30, "UPDATE_DATA": 0x31, "UPDATE_END": 0x32,
             "SET_POSITION": 0x33, "SHARE": 0x34, "SHARE_GROUP": 0x35, "UPDATE_BOOTLOADER": 0x36,
             "WIPE": 0x37, "RESTART": 0x38}
    L.append("static const struct allowed_case allowed[] = {")
    for c in v["allowed"]:
        setting = c["setting"] if c["setting"] is not None else 0
        L.append(f"    {{0x{types[c['type']]:02x}, {setting}, {'true' if c['allowed'] else 'false'}}},")
    L.append("};")
    L.append("static const struct notice_case notices[] = {")
    for c in v["notices"]:
        L.append(f"    {{{hexbytes(c['contact'])}, {c['owner']}, {c['by']}, {hexbytes(c['content'])}}},")
    L.append("};")
    L.append("static const struct locked_case locked[] = {")
    for c in v["locked"]:
        L.append(f"    {{0x{types[c['type']]:02x}, {'true' if c['allowed'] else 'false'}}},")
    L.append("};")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
